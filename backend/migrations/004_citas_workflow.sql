-- Appointment status transitions and physician-approved rescheduling.
-- Pending requests reserve the proposed physician/time until accepted or rejected.

CREATE TABLE IF NOT EXISTS public.solicitudes_cambio_cita (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cita_id bigint NOT NULL REFERENCES public.citas(id) ON DELETE CASCADE,
    paciente_id bigint NOT NULL REFERENCES public.pacientes(id) ON DELETE CASCADE,
    medico_actual_id bigint NOT NULL REFERENCES public.medicos(id) ON DELETE CASCADE,
    medico_solicitado_id bigint NOT NULL REFERENCES public.medicos(id) ON DELETE CASCADE,
    fecha_hora_solicitada timestamptz NOT NULL,
    duracion_minutos integer NOT NULL DEFAULT 30 CHECK (duracion_minutos BETWEEN 1 AND 1440),
    estado text NOT NULL DEFAULT 'pendiente'
        CHECK (estado IN ('pendiente', 'aceptada', 'rechazada')),
    motivo text,
    creado_en timestamptz NOT NULL DEFAULT now(),
    resuelto_en timestamptz,
    resuelto_por bigint REFERENCES public.usuarios(id)
);

CREATE INDEX IF NOT EXISTS solicitudes_cambio_cita_cita_idx
ON public.solicitudes_cambio_cita (cita_id, estado);

CREATE INDEX IF NOT EXISTS solicitudes_cambio_cita_reserva_idx
ON public.solicitudes_cambio_cita (medico_solicitado_id, fecha_hora_solicitada, estado);

ALTER TABLE public.solicitudes_cambio_cita ENABLE ROW LEVEL SECURITY;

CREATE OR REPLACE FUNCTION public.solicitar_cambio_cita(
    p_cita_id bigint,
    p_paciente_id bigint,
    p_medico_solicitado_id bigint,
    p_fecha_hora_solicitada timestamptz,
    p_duracion_minutos integer DEFAULT 30,
    p_motivo text DEFAULT NULL
)
RETURNS public.solicitudes_cambio_cita
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    cita_actual public.citas;
    solicitud public.solicitudes_cambio_cita;
    fin_solicitado timestamptz;
BEGIN
    IF p_fecha_hora_solicitada <= now() THEN
        RAISE EXCEPTION 'La nueva fecha y hora deben ser futuras';
    END IF;
    IF p_duracion_minutos < 1 OR p_duracion_minutos > 1440 THEN
        RAISE EXCEPTION 'La duración de la cita no es válida';
    END IF;

    SELECT * INTO cita_actual
    FROM public.citas
    WHERE id = p_cita_id AND paciente_id = p_paciente_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'La cita no pertenece al paciente o no existe';
    END IF;
    IF lower(coalesce(cita_actual.estado, '')) IN ('cancelada', 'cancelado', 'rechazada', 'rejected') THEN
        RAISE EXCEPTION 'No se puede modificar una cita cancelada o rechazada';
    END IF;
    IF EXISTS (
        SELECT 1 FROM public.solicitudes_cambio_cita
        WHERE cita_id = p_cita_id AND estado = 'pendiente'
    ) THEN
        RAISE EXCEPTION 'La cita ya tiene una solicitud de cambio pendiente';
    END IF;

    fin_solicitado := p_fecha_hora_solicitada + make_interval(mins => p_duracion_minutos);

    IF EXISTS (
        SELECT 1
        FROM public.citas c
        WHERE c.medico_id = p_medico_solicitado_id
          AND c.id <> p_cita_id
          AND lower(coalesce(c.estado, '')) NOT IN ('cancelada', 'cancelado', 'rechazada', 'rejected')
          AND c.fecha_hora < fin_solicitado
          AND c.fecha_hora + make_interval(mins => COALESCE(p_duracion_minutos, 30)) > p_fecha_hora_solicitada
    ) THEN
        RAISE EXCEPTION 'El horario solicitado ya está ocupado por otra cita';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM public.solicitudes_cambio_cita s
        WHERE s.medico_solicitado_id = p_medico_solicitado_id
          AND s.estado = 'pendiente'
          AND s.cita_id <> p_cita_id
          AND s.fecha_hora_solicitada < fin_solicitado
          AND s.fecha_hora_solicitada + make_interval(mins => s.duracion_minutos) > p_fecha_hora_solicitada
    ) THEN
        RAISE EXCEPTION 'El horario solicitado está reservado por otra solicitud pendiente';
    END IF;

    INSERT INTO public.solicitudes_cambio_cita (
        cita_id, paciente_id, medico_actual_id, medico_solicitado_id,
        fecha_hora_solicitada, duracion_minutos, motivo
    ) VALUES (
        p_cita_id, p_paciente_id, cita_actual.medico_id, p_medico_solicitado_id,
        p_fecha_hora_solicitada, p_duracion_minutos, nullif(trim(p_motivo), '')
    ) RETURNING * INTO solicitud;

    RETURN solicitud;
END;
$$;

CREATE OR REPLACE FUNCTION public.resolver_cambio_cita(
    p_solicitud_id bigint,
    p_medico_id bigint,
    p_aceptar boolean,
    p_usuario_id bigint
)
RETURNS public.solicitudes_cambio_cita
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    solicitud public.solicitudes_cambio_cita;
    fin_solicitado timestamptz;
BEGIN
    SELECT * INTO solicitud
    FROM public.solicitudes_cambio_cita
    WHERE id = p_solicitud_id AND medico_actual_id = p_medico_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Solicitud no encontrada o no pertenece al médico';
    END IF;
    IF solicitud.estado <> 'pendiente' THEN
        RAISE EXCEPTION 'La solicitud ya fue resuelta';
    END IF;

    IF p_aceptar THEN
        fin_solicitado := solicitud.fecha_hora_solicitada + make_interval(mins => solicitud.duracion_minutos);
        IF EXISTS (
            SELECT 1 FROM public.citas c
            WHERE c.medico_id = solicitud.medico_solicitado_id
              AND c.id <> solicitud.cita_id
              AND lower(coalesce(c.estado, '')) NOT IN ('cancelada', 'cancelado', 'rechazada', 'rejected')
              AND c.fecha_hora < fin_solicitado
              AND c.fecha_hora + make_interval(mins => solicitud.duracion_minutos) > solicitud.fecha_hora_solicitada
        ) THEN
            RAISE EXCEPTION 'El horario ya no está disponible';
        END IF;

        UPDATE public.citas
        SET medico_id = solicitud.medico_solicitado_id,
            fecha_hora = solicitud.fecha_hora_solicitada,
            estado = 'reprogramada'
        WHERE id = solicitud.cita_id;
        solicitud.estado := 'aceptada';
    ELSE
        solicitud.estado := 'rechazada';
    END IF;

    UPDATE public.solicitudes_cambio_cita
    SET estado = solicitud.estado, resuelto_en = now(), resuelto_por = p_usuario_id
    WHERE id = p_solicitud_id
    RETURNING * INTO solicitud;
    RETURN solicitud;
END;
$$;

REVOKE ALL ON FUNCTION public.solicitar_cambio_cita(bigint, bigint, bigint, timestamptz, integer, text) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.resolver_cambio_cita(bigint, bigint, boolean, bigint) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.solicitar_cambio_cita(bigint, bigint, bigint, timestamptz, integer, text) TO service_role;
GRANT EXECUTE ON FUNCTION public.resolver_cambio_cita(bigint, bigint, boolean, bigint) TO service_role;
