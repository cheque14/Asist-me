-- Replace 010's explicit INSERT: forwarding the subject in the HTTP payload
-- alone is insufficient, since columns omitted by that RPC become NULL.
CREATE OR REPLACE FUNCTION public.crear_cita_validada(p_datos jsonb)
RETURNS public.citas LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE datos public.citas; resultado public.citas;
BEGIN
  datos := jsonb_populate_record(NULL::public.citas, p_datos);
  datos.es_para_otra_persona := coalesce(datos.es_para_otra_persona, false);
  INSERT INTO public.citas(paciente_id, medico_id, fecha_hora, estado, motivo,
    es_para_otra_persona, beneficiario_nombre, beneficiario_telefono,
    servicio_id, tipo_cita_id, persona_atendida_id)
  VALUES (datos.paciente_id, datos.medico_id, datos.fecha_hora, datos.estado, datos.motivo,
    datos.es_para_otra_persona, datos.beneficiario_nombre, datos.beneficiario_telefono,
    datos.servicio_id, datos.tipo_cita_id, datos.persona_atendida_id)
  RETURNING * INTO resultado;
  RETURN resultado;
END;
$$;
REVOKE ALL ON FUNCTION public.crear_cita_validada(jsonb) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.crear_cita_validada(jsonb) TO service_role;

