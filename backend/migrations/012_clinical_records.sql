CREATE OR REPLACE FUNCTION public.clinical_cita_identidad()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE subject public.personas_atendidas; holder_name text; holder_phone text;
BEGIN
  IF TG_OP = 'UPDATE' THEN
    -- Serialize identity transfer with any note/DOB write for the old subject.
    PERFORM 1 FROM public.personas_atendidas p WHERE p.id = OLD.persona_atendida_id FOR UPDATE;
    IF (NEW.persona_atendida_id IS DISTINCT FROM OLD.persona_atendida_id
      OR NEW.paciente_id IS DISTINCT FROM OLD.paciente_id
      OR NEW.es_para_otra_persona IS DISTINCT FROM OLD.es_para_otra_persona
      OR NEW.beneficiario_nombre IS DISTINCT FROM OLD.beneficiario_nombre
      OR NEW.beneficiario_telefono IS DISTINCT FROM OLD.beneficiario_telefono)
      AND EXISTS (SELECT 1 FROM public.notas_clinicas n
        WHERE n.persona_id = OLD.persona_atendida_id OR n.cita_id = OLD.id) THEN
      RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'La identidad con notas clínicas no se puede reasignar';
    END IF;
  END IF;
  IF NEW.persona_atendida_id IS NULL THEN
    IF NEW.es_para_otra_persona IS TRUE THEN
      IF nullif(btrim(NEW.beneficiario_nombre), '') IS NULL
        OR length(NEW.beneficiario_nombre) > 200 OR length(coalesce(NEW.beneficiario_telefono,'')) > 32 THEN
        RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'Datos del beneficiario no válidos';
      END IF;
      INSERT INTO public.personas_atendidas(paciente_id, tipo, nombre, telefono)
      VALUES (NEW.paciente_id, 'beneficiario', btrim(NEW.beneficiario_nombre), coalesce(NEW.beneficiario_telefono,''))
      RETURNING id INTO NEW.persona_atendida_id;
    ELSE
      SELECT left(coalesce(nullif(btrim(concat_ws(' ',u.nombres,u.apellidos)),''),'Titular'),200),
        left(coalesce(u.telefono,''),32) INTO holder_name, holder_phone
      FROM public.pacientes p JOIN public.usuarios u ON u.id = p.usuario_id WHERE p.id = NEW.paciente_id;
      IF NOT FOUND THEN
        RAISE EXCEPTION USING ERRCODE = '23503', MESSAGE = 'Paciente no válido';
      END IF;
      INSERT INTO public.personas_atendidas(paciente_id,tipo,nombre,telefono)
      VALUES (NEW.paciente_id,'titular',holder_name,holder_phone)
      ON CONFLICT (paciente_id) WHERE tipo = 'titular' DO NOTHING;
      SELECT p.id INTO NEW.persona_atendida_id FROM public.personas_atendidas p
        WHERE p.paciente_id = NEW.paciente_id AND p.tipo = 'titular';
    END IF;
  END IF;
  SELECT * INTO subject FROM public.personas_atendidas p WHERE p.id = NEW.persona_atendida_id FOR SHARE;
  IF NOT FOUND OR subject.paciente_id IS DISTINCT FROM NEW.paciente_id
    OR (subject.tipo = 'beneficiario') IS DISTINCT FROM coalesce(NEW.es_para_otra_persona,false) THEN
    RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'La persona no corresponde a la cuenta y tipo de cita';
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS citas_clinical_identidad ON public.citas;
CREATE TRIGGER citas_clinical_identidad
  BEFORE INSERT OR UPDATE OF persona_atendida_id,paciente_id,es_para_otra_persona,beneficiario_nombre,beneficiario_telefono
  ON public.citas FOR EACH ROW EXECUTE FUNCTION public.clinical_cita_identidad();

CREATE OR REPLACE FUNCTION public.clinical_persona_identidad()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
  IF NEW.id IS DISTINCT FROM OLD.id OR NEW.paciente_id IS DISTINCT FROM OLD.paciente_id
    OR NEW.tipo IS DISTINCT FROM OLD.tipo OR NEW.legacy_cita_id IS DISTINCT FROM OLD.legacy_cita_id THEN
    RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'La identidad clínica es estable';
  END IF;
  IF (NEW.nombre IS DISTINCT FROM OLD.nombre OR NEW.telefono IS DISTINCT FROM OLD.telefono)
    AND EXISTS (SELECT 1 FROM public.notas_clinicas n WHERE n.persona_id = OLD.id) THEN
    RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'La identidad con notas clínicas no se puede reasignar';
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS personas_clinical_identidad ON public.personas_atendidas;
CREATE TRIGGER personas_clinical_identidad BEFORE UPDATE ON public.personas_atendidas
  FOR EACH ROW EXECUTE FUNCTION public.clinical_persona_identidad();

-- Trusted backend supplies application usuario_id. Never expose these RPCs to browsers.
CREATE OR REPLACE FUNCTION public.clinical_autorizar(
  p_usuario_id bigint, p_persona_id bigint, p_escritura boolean DEFAULT false, p_cita_id bigint DEFAULT NULL
) RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE subject public.personas_atendidas; actor_role text; actor_profile bigint; related bigint;
BEGIN
  SELECT * INTO subject FROM public.personas_atendidas p WHERE p.id = p_persona_id;
  IF NOT FOUND THEN RAISE EXCEPTION USING ERRCODE = 'P0002', MESSAGE = 'Persona no encontrada'; END IF;
  SELECT u.rol INTO actor_role FROM public.usuarios u WHERE u.id = p_usuario_id;
  IF actor_role = 'paciente' AND NOT p_escritura THEN
    SELECT p.id INTO actor_profile FROM public.pacientes p WHERE p.usuario_id = p_usuario_id;
    IF actor_profile = subject.paciente_id AND subject.tipo = 'titular' THEN RETURN NULL; END IF;
  ELSIF actor_role = 'medico' THEN
    SELECT m.id INTO actor_profile FROM public.medicos m WHERE m.usuario_id = p_usuario_id;
    -- Appointment row locks serialize note writes with cancellation/identity transfers.
    SELECT c.id INTO related FROM public.citas c
    WHERE c.medico_id = actor_profile AND c.persona_atendida_id = p_persona_id
      AND c.paciente_id = subject.paciente_id AND c.estado IN ('confirmada','reprogramada','completada')
      AND (p_cita_id IS NULL OR c.id = p_cita_id)
    ORDER BY c.id LIMIT 1 FOR SHARE;
    IF FOUND THEN
      IF p_escritura THEN
        PERFORM 1 FROM public.personas_atendidas p WHERE p.id = p_persona_id FOR UPDATE;
      ELSE
        PERFORM 1 FROM public.personas_atendidas p WHERE p.id = p_persona_id FOR SHARE;
      END IF;
      RETURN actor_profile;
    END IF;
  END IF;
  RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'Acceso clínico denegado';
END $$;

