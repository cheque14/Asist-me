CREATE OR REPLACE FUNCTION public.clinical_validar_nota()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE doctor_user bigint; vital record; value text;
BEGIN
  SELECT m.usuario_id INTO doctor_user FROM public.medicos m WHERE m.id = NEW.medico_id;
  PERFORM public.clinical_autorizar(doctor_user,NEW.persona_id,true,NEW.cita_id);
  SELECT left(coalesce(nullif(btrim(concat_ws(' ',u.nombres,u.apellidos)),''),
    nullif(u.username,''),'Médico'),200) INTO NEW.autor_nombre
    FROM public.usuarios u WHERE u.id = doctor_user;
  NEW.creado_en := clock_timestamp();
  IF jsonb_typeof(NEW.signos_vitales) IS DISTINCT FROM 'object' THEN
    RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'Signos vitales no válidos';
  END IF;
  FOR vital IN SELECT * FROM jsonb_each(NEW.signos_vitales) LOOP
    IF vital.key NOT IN ('peso_kg','talla_cm','temperatura_c','frecuencia_cardiaca','presion_arterial','saturacion_oxigeno')
      OR jsonb_typeof(vital.value) <> 'string' THEN
      RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'Signos vitales no válidos';
    END IF;
    value := vital.value #>> '{}';
    IF length(value) > 32 THEN
      RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'Signos vitales no válidos';
    END IF;
    IF value <> '' THEN
      IF vital.key = 'presion_arterial' THEN
        IF value !~ '^[0-9]{1,3}/[0-9]{1,3}$' THEN
          RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'Presión no válida';
        END IF;
        IF split_part(value,'/',1)::numeric <= 0 OR split_part(value,'/',2)::numeric <= 0 THEN
          RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'Presión no válida';
        END IF;
      ELSE
        IF value !~ '^[0-9]{1,4}(\.[0-9]{1,3})?$' THEN
          RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'Signo vital no válido';
        END IF;
        IF value::numeric <= 0 THEN
          RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'Signo vital no válido';
        END IF;
      END IF;
    END IF;
  END LOOP;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS notas_clinicas_validar ON public.notas_clinicas;
CREATE TRIGGER notas_clinicas_validar BEFORE INSERT ON public.notas_clinicas
  FOR EACH ROW EXECUTE FUNCTION public.clinical_validar_nota();

CREATE OR REPLACE FUNCTION public.clinical_personas(p_usuario_id bigint)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE actor_role text; actor_profile bigint; result jsonb;
BEGIN
  SELECT u.rol INTO actor_role FROM public.usuarios u WHERE u.id = p_usuario_id;
  IF actor_role = 'paciente' THEN
    SELECT p.id INTO actor_profile FROM public.pacientes p WHERE p.usuario_id = p_usuario_id;
    SELECT coalesce(jsonb_agg(jsonb_build_object('id',p.id,'paciente_id',p.paciente_id,'tipo',p.tipo,
      'nombre',p.nombre,'telefono',p.telefono,'fecha_nacimiento',
      CASE WHEN p.tipo = 'titular' THEN p.fecha_nacimiento ELSE NULL END,
      'acceso_clinico',p.tipo = 'titular') ORDER BY p.id),'[]'::jsonb) INTO result
    FROM public.personas_atendidas p WHERE p.paciente_id = actor_profile;
  ELSIF actor_role = 'medico' THEN
    SELECT m.id INTO actor_profile FROM public.medicos m WHERE m.usuario_id = p_usuario_id;
    SELECT coalesce(jsonb_agg(jsonb_build_object('id',p.id,'paciente_id',p.paciente_id,'tipo',p.tipo,
      'nombre',p.nombre,'telefono',p.telefono,'fecha_nacimiento',p.fecha_nacimiento,
      'acceso_clinico',true) ORDER BY p.id),'[]'::jsonb) INTO result
    FROM public.personas_atendidas p WHERE EXISTS (SELECT 1 FROM public.citas c
      WHERE c.persona_atendida_id = p.id AND c.paciente_id = p.paciente_id
        AND c.medico_id = actor_profile AND c.estado IN ('confirmada','reprogramada','completada'));
  ELSE
    RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'Acceso clínico denegado';
  END IF;
  IF actor_profile IS NULL THEN
    RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'Perfil no válido';
  END IF;
  RETURN result;
END $$;

CREATE OR REPLACE FUNCTION public.clinical_expediente(
  p_usuario_id bigint, p_persona_id bigint, p_limit integer DEFAULT 50, p_offset integer DEFAULT 0
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE result jsonb; doctor_id bigint;
BEGIN
  IF p_limit IS NULL OR p_limit NOT BETWEEN 1 AND 100 OR p_offset IS NULL OR p_offset NOT BETWEEN 0 AND 1000000 THEN
    RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'Paginación no válida';
  END IF;
  doctor_id := public.clinical_autorizar(p_usuario_id,p_persona_id,false);
  -- One statement snapshot for total and page; a scalar JSON result avoids PostgREST row caps.
  WITH page AS (SELECT n.* FROM public.notas_clinicas n WHERE n.persona_id = p_persona_id
    ORDER BY n.creado_en,n.id LIMIT p_limit OFFSET p_offset),
  totals AS (SELECT count(*) AS total FROM public.notas_clinicas n WHERE n.persona_id = p_persona_id)
  SELECT jsonb_build_object('persona',jsonb_build_object('id',p.id,'paciente_id',p.paciente_id,'tipo',p.tipo,
    'nombre',p.nombre,'telefono',p.telefono,'fecha_nacimiento',p.fecha_nacimiento,'acceso_clinico',true),
    'notas',coalesce((SELECT jsonb_agg(to_jsonb(page) ORDER BY page.creado_en,page.id) FROM page),'[]'::jsonb),
    'citas',coalesce((SELECT jsonb_agg(jsonb_build_object('id',c.id,'fecha_hora',c.fecha_hora,
      'estado',c.estado,'zona_horaria',m.zona_horaria) ORDER BY c.fecha_hora,c.id)
      FROM public.citas c JOIN public.medicos m ON m.id = c.medico_id
      WHERE c.persona_atendida_id = p.id AND c.paciente_id = p.paciente_id
        AND (doctor_id IS NULL OR c.medico_id = doctor_id)
        AND c.estado IN ('confirmada','reprogramada','completada')),'[]'::jsonb),
    'paginacion',jsonb_build_object('limit',p_limit,'offset',p_offset,'total',totals.total,
      'has_more',p_offset::bigint + p_limit < totals.total)) INTO result
  FROM public.personas_atendidas p CROSS JOIN totals WHERE p.id = p_persona_id;
  RETURN result;
END $$;

CREATE OR REPLACE FUNCTION public.clinical_agregar_nota(
  p_usuario_id bigint, p_persona_id bigint, p_datos jsonb
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE doctor_id bigint; appointment_id bigint; note public.notas_clinicas; field record;
BEGIN
  IF jsonb_typeof(p_datos) IS DISTINCT FROM 'object' OR octet_length(p_datos::text) > 48000 THEN
    RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'Nota no válida';
  END IF;
  FOR field IN SELECT * FROM jsonb_each(p_datos) LOOP
    IF field.key NOT IN ('antecedentes','alergias','motivo','exploracion','diagnostico','tratamiento',
                         'seguimiento','signos_vitales','cita_id') THEN
      RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'Campo no permitido';
    END IF;
    IF field.key NOT IN ('signos_vitales','cita_id') AND jsonb_typeof(field.value) <> 'string' THEN
      RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'El campo debe ser texto';
    END IF;
  END LOOP;
  IF p_datos ? 'cita_id' THEN
    IF jsonb_typeof(p_datos->'cita_id') <> 'number' OR (p_datos->>'cita_id') !~ '^[0-9]{1,19}$' THEN
      RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'Cita no válida';
    END IF;
    appointment_id := (p_datos->>'cita_id')::bigint;
    IF appointment_id <= 0 THEN RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'Cita no válida'; END IF;
  END IF;
  doctor_id := public.clinical_autorizar(p_usuario_id,p_persona_id,true,appointment_id);
  INSERT INTO public.notas_clinicas(persona_id,medico_id,cita_id,autor_nombre,
    antecedentes,alergias,motivo,exploracion,diagnostico,tratamiento,seguimiento,signos_vitales)
  VALUES (p_persona_id,doctor_id,appointment_id,'server',
    coalesce(p_datos->>'antecedentes',''),coalesce(p_datos->>'alergias',''),
    coalesce(p_datos->>'motivo',''),coalesce(p_datos->>'exploracion',''),coalesce(p_datos->>'diagnostico',''),
    coalesce(p_datos->>'tratamiento',''),coalesce(p_datos->>'seguimiento',''),
    coalesce(p_datos->'signos_vitales','{}'::jsonb)) RETURNING * INTO note;
  RETURN jsonb_build_object('nota',to_jsonb(note));
END $$;

CREATE OR REPLACE FUNCTION public.clinical_actualizar_persona(
  p_usuario_id bigint, p_persona_id bigint, p_fecha_nacimiento date
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE subject public.personas_atendidas;
BEGIN
  PERFORM public.clinical_autorizar(p_usuario_id,p_persona_id,true);
  IF p_fecha_nacimiento IS NOT NULL AND (p_fecha_nacimiento < DATE '1900-01-01' OR p_fecha_nacimiento > CURRENT_DATE) THEN
    RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'Fecha de nacimiento no válida';
  END IF;
  UPDATE public.personas_atendidas SET fecha_nacimiento = p_fecha_nacimiento
    WHERE id = p_persona_id RETURNING * INTO subject;
  RETURN jsonb_build_object('persona',jsonb_build_object('id',subject.id,'paciente_id',subject.paciente_id,
    'tipo',subject.tipo,'nombre',subject.nombre,'telefono',subject.telefono,
    'fecha_nacimiento',subject.fecha_nacimiento,'acceso_clinico',true));
END $$;

