CREATE OR REPLACE FUNCTION public.proponer_cambio_cita(
    p_cita_id bigint,
    p_medico_id bigint,
    p_fecha_hora_solicitada timestamptz,
    p_motivo text DEFAULT NULL
)
RETURNS public.solicitudes_cambio_cita
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public
AS $$
DECLARE
  cita_actual public.citas;
  propuesta public.solicitudes_cambio_cita;
BEGIN
  IF p_fecha_hora_solicitada <= now() THEN
    RAISE EXCEPTION 'La nueva fecha y hora deben ser futuras';
  END IF;
  SELECT * INTO cita_actual FROM public.citas
  WHERE id = p_cita_id AND medico_id = p_medico_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'La cita no pertenece al médico o no existe'; END IF;
  IF lower(coalesce(cita_actual.estado, '')) IN ('cancelada', 'rechazada') THEN
    RAISE EXCEPTION 'No se puede modificar una cita cancelada o rechazada';
  END IF;
  IF EXISTS (SELECT 1 FROM public.solicitudes_cambio_cita
             WHERE cita_id = p_cita_id AND estado IN ('pendiente','pendiente_paciente','pendiente_medico')) THEN
    RAISE EXCEPTION 'La cita ya tiene una propuesta pendiente';
  END IF;
  IF EXISTS (
    SELECT 1 FROM public.citas c
    WHERE c.medico_id = p_medico_id AND c.id <> p_cita_id
      AND lower(coalesce(c.estado, '')) NOT IN ('cancelada','rechazada')
      AND c.fecha_hora BETWEEN p_fecha_hora_solicitada - interval '29 minutes'
                           AND p_fecha_hora_solicitada + interval '29 minutes'
  ) THEN RAISE EXCEPTION 'El horario solicitado ya está ocupado'; END IF;

  INSERT INTO public.solicitudes_cambio_cita
    (cita_id, paciente_id, medico_actual_id, medico_solicitado_id, fecha_hora_solicitada,
     duracion_minutos, estado, motivo, solicitante_rol)
  VALUES (p_cita_id, cita_actual.paciente_id, p_medico_id, p_medico_id,
          p_fecha_hora_solicitada, 30, 'pendiente_paciente', nullif(trim(p_motivo), ''), 'medico')
  RETURNING * INTO propuesta;

  BEGIN
    INSERT INTO public.notificaciones (usuario_id, cita_id, tipo, mensaje)
    SELECT p.usuario_id, p_cita_id, 'propuesta_cita',
           'Tu médico propuso cambiar la fecha u hora de tu cita. Revisa la propuesta.'
    FROM public.pacientes p WHERE p.id = cita_actual.paciente_id;
  EXCEPTION WHEN OTHERS THEN
    RAISE NOTICE 'No se pudo crear la notificación de propuesta: %', SQLERRM;
  END;
  RETURN propuesta;
END;
$$;

CREATE OR REPLACE FUNCTION public.resolver_propuesta_cita_paciente(
    p_solicitud_id bigint,
    p_paciente_id bigint,
    p_accion text,
    p_fecha_hora_contraoferta timestamptz DEFAULT NULL
)
RETURNS public.solicitudes_cambio_cita
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public
AS $$
DECLARE
  propuesta public.solicitudes_cambio_cita;
BEGIN
  SELECT * INTO propuesta FROM public.solicitudes_cambio_cita
  WHERE id = p_solicitud_id AND paciente_id = p_paciente_id FOR UPDATE;
  IF NOT FOUND
     OR propuesta.estado NOT IN ('pendiente_paciente', 'pendiente')
     OR propuesta.solicitante_rol <> 'medico' THEN
    RAISE EXCEPTION 'La propuesta no existe o ya fue resuelta';
  END IF;
  IF p_accion = 'aceptar' THEN
    UPDATE public.citas SET fecha_hora = propuesta.fecha_hora_solicitada, estado = 'reprogramada'
    WHERE id = propuesta.cita_id;
    propuesta.estado := 'aceptada';
  ELSIF p_accion = 'rechazar' THEN
    propuesta.estado := 'rechazada';
  ELSIF p_accion = 'contraofertar' THEN
    IF p_fecha_hora_contraoferta IS NULL OR p_fecha_hora_contraoferta <= now() THEN
      RAISE EXCEPTION 'La contraoferta debe tener una fecha futura';
    END IF;
    IF EXISTS (
      SELECT 1 FROM public.citas c
      WHERE c.medico_id = propuesta.medico_actual_id AND c.id <> propuesta.cita_id
        AND lower(coalesce(c.estado, '')) NOT IN ('cancelada','rechazada')
        AND c.fecha_hora BETWEEN p_fecha_hora_contraoferta - interval '29 minutes'
                             AND p_fecha_hora_contraoferta + interval '29 minutes'
    ) THEN RAISE EXCEPTION 'El horario propuesto ya está ocupado'; END IF;
    UPDATE public.solicitudes_cambio_cita
    SET fecha_hora_solicitada = p_fecha_hora_contraoferta,
        estado = 'pendiente_medico', respuesta = 'contraoferta', resuelto_en = NULL
    WHERE id = p_solicitud_id RETURNING * INTO propuesta;
    BEGIN
      INSERT INTO public.notificaciones (usuario_id, cita_id, tipo, mensaje)
      SELECT m.usuario_id, propuesta.cita_id, 'contraoferta_cita',
             'El paciente propuso otro horario para la cita. Revisa y decide.'
      FROM public.medicos m WHERE m.id = propuesta.medico_actual_id;
    EXCEPTION WHEN OTHERS THEN
      RAISE NOTICE 'No se pudo crear la notificación de contraoferta: %', SQLERRM;
    END;
    RETURN propuesta;
  ELSE
    RAISE EXCEPTION 'La acción no es válida';
  END IF;
  UPDATE public.solicitudes_cambio_cita
  SET estado = propuesta.estado, respuesta = p_accion, resuelto_en = now()
  WHERE id = p_solicitud_id RETURNING * INTO propuesta;
  BEGIN
    INSERT INTO public.notificaciones (usuario_id, cita_id, tipo, mensaje)
    SELECT m.usuario_id, propuesta.cita_id,
           'respuesta_cita', CASE WHEN p_accion = 'aceptar'
             THEN 'El paciente aceptó el cambio de horario.'
             ELSE 'El paciente rechazó el cambio de horario.' END
    FROM public.medicos m WHERE m.id = propuesta.medico_actual_id;
  EXCEPTION WHEN OTHERS THEN
    RAISE NOTICE 'No se pudo crear la notificación de respuesta: %', SQLERRM;
  END;
  RETURN propuesta;
END;
$$;

GRANT EXECUTE ON FUNCTION public.proponer_cambio_cita(bigint,bigint,timestamptz,text) TO service_role;
GRANT EXECUTE ON FUNCTION public.resolver_propuesta_cita_paciente(bigint,bigint,text,timestamptz) TO service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO service_role;
GRANT SELECT, INSERT, UPDATE ON public.notificaciones TO service_role;

CREATE OR REPLACE FUNCTION public.resolver_cambio_cita(
    p_solicitud_id bigint, p_medico_id bigint, p_aceptar boolean, p_usuario_id bigint
)
RETURNS public.solicitudes_cambio_cita
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public
AS $$
DECLARE
  solicitud public.solicitudes_cambio_cita;
BEGIN
  SELECT * INTO solicitud FROM public.solicitudes_cambio_cita
  WHERE id = p_solicitud_id AND medico_actual_id = p_medico_id FOR UPDATE;
  IF NOT FOUND OR solicitud.estado NOT IN ('pendiente','pendiente_medico') THEN
    RAISE EXCEPTION 'Solicitud no encontrada o ya fue resuelta';
  END IF;
  IF p_aceptar THEN
    IF EXISTS (
      SELECT 1 FROM public.citas c
      WHERE c.medico_id = solicitud.medico_solicitado_id AND c.id <> solicitud.cita_id
        AND lower(coalesce(c.estado, '')) NOT IN ('cancelada','rechazada')
        AND c.fecha_hora BETWEEN solicitud.fecha_hora_solicitada - interval '29 minutes'
                             AND solicitud.fecha_hora_solicitada + interval '29 minutes'
    ) THEN RAISE EXCEPTION 'El horario ya no está disponible'; END IF;
    UPDATE public.citas SET medico_id = solicitud.medico_solicitado_id,
      fecha_hora = solicitud.fecha_hora_solicitada, estado = 'reprogramada'
    WHERE id = solicitud.cita_id;
    solicitud.estado := 'aceptada';
  ELSE
    solicitud.estado := 'rechazada';
  END IF;
  UPDATE public.solicitudes_cambio_cita
  SET estado = solicitud.estado, respuesta = CASE WHEN p_aceptar THEN 'aceptar' ELSE 'rechazar' END,
      resuelto_en = now(), resuelto_por = p_usuario_id
  WHERE id = p_solicitud_id RETURNING * INTO solicitud;
  BEGIN
    INSERT INTO public.notificaciones (usuario_id, cita_id, tipo, mensaje)
    SELECT p.usuario_id, solicitud.cita_id, 'respuesta_cita',
           CASE WHEN p_aceptar THEN 'El médico aceptó tu cambio de cita.'
                ELSE 'El médico rechazó tu cambio de cita.' END
    FROM public.pacientes p WHERE p.id = solicitud.paciente_id;
  EXCEPTION WHEN OTHERS THEN
    RAISE NOTICE 'No se pudo crear la notificación de respuesta: %', SQLERRM;
  END;
  RETURN solicitud;
END;
$$;

GRANT EXECUTE ON FUNCTION public.resolver_cambio_cita(bigint,bigint,boolean,bigint) TO service_role;
