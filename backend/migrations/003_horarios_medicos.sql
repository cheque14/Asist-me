ALTER TABLE public.medicos
ADD COLUMN IF NOT EXISTS zona_horaria text NOT NULL DEFAULT 'UTC';

CREATE TABLE IF NOT EXISTS public.horarios_medico (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medico_id bigint NOT NULL REFERENCES public.medicos(id) ON DELETE CASCADE,
    dia_semana smallint NOT NULL CHECK (dia_semana BETWEEN 0 AND 6),
    hora_inicio time NOT NULL,
    hora_fin time NOT NULL,
    CONSTRAINT horarios_medico_horas_validas CHECK (hora_inicio < hora_fin)
);

CREATE INDEX IF NOT EXISTS horarios_medico_medico_dia_idx
ON public.horarios_medico (medico_id, dia_semana, hora_inicio);

ALTER TABLE public.horarios_medico ENABLE ROW LEVEL SECURITY;

CREATE OR REPLACE FUNCTION public.reemplazar_horario_medico(
    p_medico_id bigint,
    p_zona_horaria text,
    p_horarios jsonb
)
RETURNS void
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public
AS $$
DECLARE
    medico_actualizado integer;
BEGIN
    UPDATE public.medicos
    SET zona_horaria = p_zona_horaria
    WHERE id = p_medico_id;

    GET DIAGNOSTICS medico_actualizado = ROW_COUNT;
    IF medico_actualizado = 0 THEN
        RAISE EXCEPTION 'Médico no encontrado';
    END IF;

    DELETE FROM public.horarios_medico
    WHERE medico_id = p_medico_id;

    INSERT INTO public.horarios_medico (medico_id, dia_semana, hora_inicio, hora_fin)
    SELECT p_medico_id, horario.dia_semana, horario.hora_inicio, horario.hora_fin
    FROM jsonb_to_recordset(p_horarios) AS horario(
        dia_semana smallint,
        hora_inicio time,
        hora_fin time
    );
END;
$$;

REVOKE ALL ON FUNCTION public.reemplazar_horario_medico(bigint, text, jsonb) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.reemplazar_horario_medico(bigint, text, jsonb) FROM anon, authenticated;
GRANT EXECUTE ON FUNCTION public.reemplazar_horario_medico(bigint, text, jsonb) TO service_role;
